%%这段代码对输入的矩阵X0进行归一化，使得矩阵中的所有非无穷大数值在0到1之间
function X0=myMapminmax(X0)
   % 进行归一化操作，当元素值非无穷的时候将矩阵中所有非无穷的元素值进行归一化处理，值域为[0,1]。
   % 归一化公式为: (x - min) / (max - min)
   % 在分母部分加入eps是为了避免除以0的情况（max与min都是同一个值时会出现这种情况）。
    X0(~isinf(X0))=(X0(~isinf(X0))-min(min(X0(~isinf(X0)))))/(max(max(X0(~isinf(X0))))-min(min(X0(~isinf(X0))))+eps);
    
    %%这一行代码被注释掉了，如果取消注释，下面这行代码将把数据的值域变为[-1,1]（因为原本的值域为[0,1]，经过*2操作后为[0,2]，再减去1后变为[-1,1]）。
    %X0=X0*2-1;
end