function batch_search_event(event,alg,data,isSearch,index)
out=getenv('BATCH_OUTPUT');if isempty(out),return;end
s=struct('event',event,'algorithm',alg,'seed',str2double(getenv('CASE1_TRIAL_SEED')),...
    'warmup',strcmp(getenv('BATCH_WARMUP'),'1'),'call_index',index,'is_search',isSearch,...
    'configuration',getenv('MULTIDIAM_CONFIG'),'diameter',data.BD,'diameter_BD1',data.BD1,...
    'stub_length',2*data.BD,'physical_start',data.S0,'physical_goal',data.E0,...
    'start',data.S,'goal',data.E,'time',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss.SSS')));
if strcmp(alg,'GFDHS'),s.planning_step_max=data.planning_step_max;s.energy_range_device=data.energy_range_device;end
f=fopen(fullfile(out,'ACTIVE_SEARCH.json.tmp'),'w','n','UTF-8');assert(f>0);fprintf(f,'%s',jsonencode(s));fclose(f);
movefile(fullfile(out,'ACTIVE_SEARCH.json.tmp'),fullfile(out,'ACTIVE_SEARCH.json'),'f');
fprintf('SEARCH %s seed=%d call=%d search=%d %s\n',alg,s.seed,index,isSearch,event);
end
