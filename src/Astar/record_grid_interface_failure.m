function record_grid_interface_failure(p,port,data,lo,hi,d,c,own,axis,sgn,axesOther)
% Save existing failed-attachment context only. No RNG, extra geometry tests,
% expanded neighborhood, alternate direction, grid write or optimizer calls.
[inputId,diameter]=case1_request_identity(data.S0,data.E0,case1_pipe_diameters());
policy=case1_constraint_policy();
assert(c==policy.interface_clearance && data.physical_collision_margin==c && data.dsafe==policy.energy_dsafe,...
    'Interface:DiagnosticPolicy','Failure diagnostics must distinguish energy dsafe from interface gap.');
assert(d==diameter && data.BD==diameter && data.BD1==diameter,...
    'Interface:DiagnosticDiameter','Failure diagnostics must use the actual request diameter.');
endpoint='';if isequal(port,double(data.S0)),endpoint='start';end
if isequal(port,double(data.E0)),endpoint='goal';end
assert(~isempty(endpoint),'Interface:DiagnosticPort','Failed connector has no original endpoint identity.');
h=data.unit;base=round(p/h)*h;
if sgn>0,base(axis)=ceil((hi(own,axis)+d/2+c)/h)*h;
else,base(axis)=floor((lo(own,axis)-d/2-c)/h)*h;end
last=base;last(axis)=base(axis)+sgn*4*h;
lower=min(base,last);upper=max(base,last);
lower(axesOther)=lower(axesOther)-h;upper(axesOther)=upper(axesOther)+h;
record=struct('stage','grid_interface_preparation','input_request_id',inputId,...
    'physical_start',data.S0,'physical_goal',data.E0,'failed_endpoint',endpoint,...
    'true_port',port,'physical_offset_port',p,'grid_h',h,...
    'diameter',diameter,'diameter_BD1',data.BD1,'dsafe',data.dsafe,...
    'energy_dsafe',data.dsafe,'physical_collision_margin',c,'interface_clearance',c,'constraint_policy_id',policy.id,...
    'stub_length',sum(abs(p-port)),'stub_length_rule','2*physical_diameter',...
    'native_outgoing_axis',axis,'native_outgoing_sign',sgn,...
    'own_stub_index_1based',own,'own_stub_lo',lo(own,:),'own_stub_hi',hi(own,:),...
    'ownership_definition','Own interface stub AABB in the pipes array; this index is not an equipment-owner index.',...
    'all_stub_lo',lo,'all_stub_hi',hi,...
    'device_lo',[data.mapx1(:),data.mapy1(:),data.mapz1(:)],...
    'device_hi',[data.mapx2(:),data.mapy2(:),data.mapz2(:)],...
    'domain',data.mapsize,'grid_array_size',size(data.map_er),...
    'fixed_layers',0:4,'fixed_transverse_offsets',-1:1,...
    'fixed_candidate_envelope_lo',lower,'fixed_candidate_envelope_hi',upper,...
    'native_grid_point_slots_considered',45,'best_empty',true,...
    'optimizer_search_calls_for_failed_request',0,...
    'definition','The unchanged deterministic attach loop exhausted its fixed 5x3x3 grid-point neighborhood with no valid connector. Stored bounds describe those same slots; grid points can be rejected before either connector ordering is tested. No additional search or repair was performed.');
assignin('base','native_failure_stage','grid_interface_preparation');
assignin('base','native_interface_details',{record});
end
