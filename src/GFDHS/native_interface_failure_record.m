function record=native_interface_failure_record(originalPair,endpoint,candidates,energy,data)
% Pure diagnostics for already evaluated native interface points; no RNG,
% extra potential calls, input repair, or substitute search attempts.
[inputId,diameter]=case1_request_identity(originalPair(1,:),originalPair(2,:),case1_pipe_diameters());
policy=case1_constraint_policy();
assert(data.dsafe==policy.energy_dsafe && data.physical_collision_margin==policy.physical_collision_margin && data.hard_clearance==data.physical_collision_margin,...
    'Multidiameter:DiagnosticPolicy','Failure diagnostics must distinguish energy dsafe from physical collision margin.');
assert(size(candidates,1)==6 && numel(energy)==6 && all(isinf(energy) & energy>0),...
    'Multidiameter:InterfaceDiagnostics','No-admissible-interface requires all six original tests to return positive Inf.');
record=struct('stage','interface_preparation','input_request_id',inputId,...
    'physical_start',originalPair(1,:),'physical_goal',originalPair(2,:),...
    'failed_endpoint',endpoint,'diameter',diameter,'diameter_BD1',data.BD1,...
    'stub_length',2*diameter,'stub_length_rule','2*physical_diameter',...
    'dsafe',data.dsafe,'hard_clearance',data.hard_clearance,...
    'energy_dsafe',data.dsafe,'physical_collision_margin',data.physical_collision_margin,'constraint_policy_id',policy.id,...
    'directions',data.dir,'native_candidate_points',candidates,...
    'native_candidate_energy',energy(:)',...
    'native_candidate_positive_infinity',isinf(energy(:)') & energy(:)'>0,...
    'native_candidate_admissible',energy(:)'~=Inf,...
    'endpoint_tests_executed',numel(energy),'optimizer_search_calls_for_failed_request',0,...
    'definition','Six original point-energy interface tests, each evaluated once; JSON null energies are explicit positive Inf flags, not missing observations. No optimizer search is attempted without an admissible native stub.');
end
