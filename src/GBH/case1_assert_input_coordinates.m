function case1_assert_input_coordinates(coordinates)
assert(isequal(size(coordinates),[9 3]),'Multidiameter:Inputs','Expected three original requests.');
assert(isequal(coordinates(1:3:end,:),[740 50 529;1055 582 529;415 136 45]) && ...
       isequal(coordinates(2:3:end,:),[249 600 138;434 1336 638;249 631 23]),...
       'Multidiameter:Inputs','True physical endpoints must not move.');
assert(isequal(coordinates(3:3:end,1),[1;1;6]) && all(coordinates(3:3:end,3)==3),...
       'Multidiameter:Inputs','Pipe type or dsafe changed.');
assert(isequal(coordinates(3:3:end,2)',case1_pipe_diameters()),...
       'Multidiameter:Inputs','Input-order diameter binding changed.');
end
